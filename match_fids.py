def normalize(s):
    s = s.strip()
    for suffix in ['FC', '队', '俱乐部', '足球俱乐部']:
        if s.endswith(suffix) and len(s) > len(suffix):
            s = s[:-len(suffix)]
    return s.strip()

def get_aliases(team):
    """Get all possible name variants for a team"""
    aliases = {team, normalize(team)}
    if team in TEAM_ALIASES:
        for a in TEAM_ALIASES[team]:
            aliases.add(a)
            aliases.add(normalize(a))
    # Also try removing spaces
    aliases.add(team.replace(' ', ''))
    return {a for a in aliases if a}

def char_overlap_score(a, b):
    """Score based on shared Chinese characters"""
    if not a or not b:
        return 0
    a_chars = set(a)
    b_chars = set(b)
    common = a_chars & b_chars
    # At least 2 shared chars
    if len(common) < 2:
        return 0
    min_len = min(len(a_chars), len(b_chars))
    if min_len == 0:
        return 0
    ratio = len(common) / min_len
    if ratio >= 0.8:
        return 90
    elif ratio >= 0.6:
        return 70
    elif ratio >= 0.4:
        return 50
    return 30

def match_team(db_team, teams_500):
    """Find the best matching 500.com team name"""
    db_alias = get_aliases(db_team)
    best_score = 0
    best_team = None
    
    for t500 in teams_500:
        for alias in db_alias:
            # Exact match
            if alias == t500:
                return (t500, 100)
            # Substring match
            if alias in t500 or t500 in alias:
                if len(alias) >= 2 and len(t500) >= 2:
                    score = 80 + max(0, 10 - abs(len(alias) - len(t500)))
                    if score > best_score:
                        best_score = score
                        best_team = t500
            # Character overlap
            score = char_overlap_score(alias, t500)
            if score > best_score:
                best_score = score
                best_team = t500
    
    return (best_team, best_score)

# Main matching
print("Loading 500.com data...")
with open('500_data.json') as f:
    raw = json.load(f)

# Index: league -> [(home, away, fid)]
league_index = {}
for league_500, home_500, away_500, fid in raw:
    league_index.setdefault(league_500, []).append((home_500, away_500, fid))

print(f"Loaded {len(raw)} entries across {len(league_index)} leagues")

# Get missing matches from DB
db = sqlite3.connect('data/football.db')
cur = db.cursor()
cur.execute("SELECT id, match_id, date, home_team, away_team, league FROM poisson_predictions WHERE fid_500 IS NULL OR fid_500 = ''")
missing = cur.fetchall()
print(f"Missing fids: {len(missing)}")

matched = []  # (id, match_id, fid)
unmatched = []

for row in missing:
    mid, match_id, dt, home, away, league = row
    
    # Try different league names
    leagues_to_try = {league, LEAGUE_MAP.get(league, league)}
    # Also try without league filtering
    
    best_fid = None
    best_h_score = 0
    best_a_score = 0
    
    # Method 1: Match by league
    for league_try in leagues_to_try:
        candidates = league_index.get(league_try, [])
        if not candidates:
            continue
        h_teams = {c[0] for c in candidates}
        a_teams = {c[1] for c in candidates}
        
        best_h_team, h_score = match_team(home, h_teams)
        best_a_team, a_score = match_team(away, a_teams)
        
        if best_h_team and best_a_team and h_score >= 70 and a_score >= 70:
            # Find matching pair
            for h500, a500, fid in candidates:
                if h500 == best_h_team and a500 == best_a_team:
                    if h_score + a_score > best_h_score + best_a_score:
                        best_fid = fid
                        best_h_score = h_score
                        best_a_score = a_score
    
    # Method 2: If not found, try without league filter (all teams)
    if not best_fid:
        all_unique_pairs = {}
        for l, entries in league_index.items():
            for h500, a500, fid in entries:
                all_unique_pairs[(h500, a500)] = fid
        
        h_teams_all = {k[0] for k in all_unique_pairs}
        a_teams_all = {k[1] for k in all_unique_pairs}
        
        best_h_team, h_score = match_team(home, h_teams_all)
        best_a_team, a_score = match_team(away, a_teams_all)
        
        if best_h_team and best_a_team and h_score >= 70 and a_score >= 70:
            fid = all_unique_pairs.get((best_h_team, best_a_team))
            if fid and h_score + a_score > best_h_score + best_a_score:
                best_fid = fid
                best_h_score = h_score
                best_a_score = a_score
    
    if best_fid and best_h_score >= 70 and best_a_score >= 70:
        matched.append((mid, match_id, best_fid))
        print(f"  ✅ {dt[:10]} {league}: {home} vs {away} -> fid={best_fid} (scores: h={best_h_score} a={best_a_score})")
    else:
        unmatched.append(row)
        if len(unmatched) <= 10:
            print(f"  ❌ {dt[:10]} {league}: {home} vs {away} (best h={best_h_score} a={best_a_score})")

print(f"\n{'='*50}")
print(f"Matched: {len(matched)}")
print(f"Unmatched: {len(unmatched)}")

